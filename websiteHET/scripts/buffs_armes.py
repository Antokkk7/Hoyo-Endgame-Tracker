# Armes de Genshin Impact dont le passif apporte un bonus chiffrable, avec les valeurs de R1 à R5 (source : genshin.gg/weapons).
# Valeurs en points de pourcentage. "v" est une liste de 5 valeurs (R1 à R5, interpolées linéairement entre R1 et R5).
# Règle des cumuls : un bonus qui demande des cumuls est pris aux 2/3 du maximum arrondi à l'entier supérieur (5 -> 3, 4 -> 2, 3 -> 2).
# Un bonus de valeur unique reste identique à tous les raffinements. Les armes marquées BP sont prises en R1 par défaut dans l'interface.
# Voir buffs_sets.py pour les champs ; cible : "soi" (porteur) ou "equipe" (aussi pour les coéquipiers).
import math

from buffs_sets import e


def L(a, b, cumuls=1):
    """Valeurs R1..R5 de a à b, multipliées par le nombre de cumuls retenu."""
    n = math.ceil(2 * cumuls / 3) if cumuls > 1 else 1
    return [round((a + (b - a) * i / 4) * n, 2) for i in range(5)]


def C(valeur):
    return [valeur] * 5


def s(stat, v, c=None, **kw):
    return e(stat, v, c, cible=kw.pop("cible", "soi"), **kw)


def t(stat, v, c=None, g=None, **kw):
    return e(stat, v, c, cible="equipe", g=g, **kw)


